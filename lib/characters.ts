let segmenter: Intl.Segmenter | null = null;

/**
 * Zählt sichtbare Zeichen statt UTF-16-Einheiten. Ein Emoji wie 👍 belegt zwei
 * Einheiten, 👨‍👩‍👧 sogar acht – ohne Segmenter läge der Zähler bei Texten mit
 * Emojis deutlich über der tatsächlichen Länge, und genau daran hängen die
 * Zeichenvorgaben in den Prompts.
 */
export function countCharacters(text: string): number {
  if (typeof Intl !== "undefined" && typeof Intl.Segmenter === "function") {
    segmenter ??= new Intl.Segmenter("de", { granularity: "grapheme" });
    let count = 0;
    for (const _segment of segmenter.segment(text)) count += 1;
    return count;
  }
  return text.length;
}
