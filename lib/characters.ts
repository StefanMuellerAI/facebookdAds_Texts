export type CharacterGroup = {
  id: string;
  label: string;
  /** Suchbegriffe je Zeichen, damit die Suche auf Deutsch funktioniert. */
  items: { char: string; keywords: string }[];
};

function group(id: string, label: string, entries: [string, string][]): CharacterGroup {
  return {
    id,
    label,
    items: entries.map(([char, keywords]) => ({ char, keywords })),
  };
}

